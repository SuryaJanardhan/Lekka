import { RuleModel, IRule } from '../models/Rule';
import { CategoryModel } from '../models/Category';
import { Types } from 'mongoose';
import { createHash } from 'crypto';
import { learningConditions } from './categoryLearning';

export class RuleEngine {
  public static async evaluateEmail(
    sender: string,
    subject: string,
    body: string
  ): Promise<Types.ObjectId | null> {
    const rules = await RuleModel.find({}).sort({ priority: -1, updatedAt: -1 }).lean();

    for (const rule of rules) {
      const isMatch = rule.conditions.every((condition) => {
        let targetValue = '';
        if (condition.field === 'sender') targetValue = sender;
        else if (condition.field === 'subject') targetValue = subject;
        else if (condition.field === 'body') targetValue = body;

        const valLower = targetValue.toLowerCase();
        const condValLower = condition.value.toLowerCase();

        switch (condition.operator) {
          case 'contains':
            return valLower.includes(condValLower);
          case 'equals':
            return valLower === condValLower;
          case 'startsWith':
            return valLower.startsWith(condValLower);
          case 'regex':
            try {
              const regex = new RegExp(condition.value, 'i');
              return regex.test(targetValue);
            } catch {
              return false;
            }
          default:
            return false;
        }
      });

      if (isMatch) {
        if (await CategoryModel.exists({ _id: rule.categoryId })) return rule.categoryId as Types.ObjectId;
      }
    }

    return null;
  }

  public static async autoGenerateRuleFromUserFeedback(
    subject: string,
    sender: string,
    categoryId: Types.ObjectId,
    merchant?: string,
    body = '',
    source: 'AI' | 'USER' = 'USER'
  ): Promise<IRule> {
    const conditions = learningConditions(sender, subject, merchant, body);
    const learningKey = createHash('sha256').update(JSON.stringify({ source, conditions })).digest('hex');
    return RuleModel.findOneAndUpdate({ learningKey }, {
      $set: { categoryId, conditions, priority: source === 'USER' ? 20 : 1, autoGenerated: true, learnedFrom: source },
      $setOnInsert: { learningKey }
    }, { upsert: true, new: true, runValidators: true });
  }
}
