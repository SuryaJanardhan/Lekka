import test from 'node:test';
import assert from 'node:assert/strict';
import { Types } from 'mongoose';
import { RuleEngine } from './ruleEngine';
import { LedgerService } from './ledgerService';
import { RuleModel } from '../models/Rule';
import { CategoryModel } from '../models/Category';
import { EmailModel } from '../models/Email';
import { notificationService } from './notificationService';

test('AI-created legacy rules cannot bypass review; a user-confirmed merchant rule can', async (t) => {
  const category = new Types.ObjectId();
  const conditions = [{ field: 'sender', operator: 'equals', value: 'bank@example.com' }, { field: 'body', operator: 'contains', value: 'Cafe' }];
  let rules: any[] = [{ categoryId: category, conditions, autoGenerated: true, learnedFrom: 'AI' }];
  t.mock.method(RuleModel, 'find', () => ({ sort() { return this; }, lean: async () => rules }));
  t.mock.method(CategoryModel, 'exists', async () => ({ _id: category }));
  assert.equal(await RuleEngine.evaluateEmail('bank@example.com', 'Receipt', 'Paid to Cafe'), null);
  rules = [{ categoryId: category, conditions, autoGenerated: true, learnedFrom: 'USER' }];
  assert.equal(await RuleEngine.evaluateEmail('bank@example.com', 'Receipt', 'Paid to Cafe'), category);
  assert.equal(await RuleEngine.evaluateEmail('bank@example.com', 'Receipt', 'Paid to Pharmacy'), null);
  assert.equal(await RuleEngine.evaluateEmail('other@example.com', 'Receipt', 'Paid to Cafe'), null);
});

test('reopening review changes only review flags, not amounts or categories', async (t) => {
  let change: any;
  const entry = { parsedJson: { detectedAmount: 30 }, categoryId: new Types.ObjectId() };
  t.mock.method(EmailModel, 'findByIdAndUpdate', (_id: string, update: any) => {
    change = update;
    return { populate: async () => entry };
  });
  assert.equal(await LedgerService.requestReview(new Types.ObjectId().toHexString()), entry);
  assert.deepEqual(change, { $set: { needsUserReview: true, reviewStatus: 'PENDING' } });
});

test('saving an edited pending entry trains its original merchant and retains receipt evidence', async (t) => {
  t.mock.method(notificationService, 'resolveCategoryReview', async () => undefined);
  const id = new Types.ObjectId();
  const entry: any = { _id: id, subject: 'Receipt', sender: 'bank@example.com', rawTextBody: 'You paid INR 30 to Cafe',
    parsedJson: { detectedAmount: 30, merchantName: 'Cafe' }, needsUserReview: true, save: async () => undefined };
  let calls = 0;
  t.mock.method(EmailModel, 'findById', () => ++calls === 1 ? Promise.resolve(entry) : { populate: async () => entry });
  const learned = t.mock.method(RuleEngine, 'autoGenerateRuleFromUserFeedback', async () => undefined);
  await LedgerService.updateEntry(id.toHexString(), { title: 'Lunch', amount: 30, categoryId: new Types.ObjectId().toHexString(), notes: 'Lunch break' });
  assert.equal(entry.needsUserReview, false);
  assert.equal(entry.categorySource, 'USER_MANUAL');
  assert.equal(entry.rawTextBody, 'You paid INR 30 to Cafe');
  assert.equal(learned.mock.callCount(), 1);
  assert.equal(learned.mock.calls[0].arguments[0], 'Receipt');
  assert.equal(learned.mock.calls[0].arguments[3], 'Cafe');
});

test('Save category confirms a pending entry and then trains the chosen category', async (t) => {
  const resolved = t.mock.method(notificationService, 'resolveCategoryReview', async () => undefined);
  const id = new Types.ObjectId();
  const category = new Types.ObjectId();
  const entry: any = { _id: id, subject: 'Receipt', sender: 'bank@example.com', rawTextBody: 'You paid INR 30 to Cafe',
    parsedJson: { merchantName: 'Cafe' }, needsUserReview: true, save: async () => undefined };
  let calls = 0;
  t.mock.method(EmailModel, 'findById', () => ++calls === 1 ? Promise.resolve(entry) : { populate: async () => entry });
  t.mock.method(CategoryModel, 'findById', async () => ({ _id: category }));
  const learned = t.mock.method(RuleEngine, 'autoGenerateRuleFromUserFeedback', async () => undefined);
  await LedgerService.assignCategory({ entryId: id.toHexString(), categoryId: category.toHexString() });
  assert.equal(entry.reviewStatus, 'APPROVED');
  assert.equal(entry.needsUserReview, false);
  assert.equal(entry.categorySource, 'USER_MANUAL');
  assert.equal(learned.mock.callCount(), 1);
  assert.equal(String(learned.mock.calls[0].arguments[2]), category.toHexString());
  assert.equal(learned.mock.calls[0].arguments[3], 'Cafe');
  assert.equal(resolved.mock.calls[0].arguments[0], id.toHexString());
});
