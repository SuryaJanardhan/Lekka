import test from 'node:test';
import assert from 'node:assert/strict';
import { Types } from 'mongoose';
import { RuleController } from './ruleController';
import { RuleModel } from '../models/Rule';
import { CategoryModel } from '../models/Category';
import { validateConditions, validatePriority } from '../services/ruleValidation';

test('editing preserves all rule conditions and makes the edited rule explicitly user controlled', async t => {
  const id = new Types.ObjectId(), categoryId = new Types.ObjectId();
  const conditions = [{ field: 'sender', operator: 'equals', value: 'bank@example.com' }, { field: 'body', operator: 'contains', value: 'HungerBox' }, { field: 'direction', operator: 'equals', value: 'DEBIT' }];
  const rule: any = { _id: id, categoryId, conditions, priority: 20, autoGenerated: true, learningKey: 'old-key', save: async () => undefined };
  let calls = 0;
  t.mock.method(RuleModel, 'findById', () => ++calls === 1 ? Promise.resolve(rule) : { populate: async () => rule });
  t.mock.method(CategoryModel, 'exists', async () => ({ _id: categoryId }));
  const res = Object.assign(Object.create(null), { code: 200, payload: null, status(code: number) { this.code = code; return this; }, json(payload: any) { this.payload = payload; return this; } });
  await RuleController.updateRule(Object.assign(Object.create(null), { params: { id: String(id) }, body: { conditions, categoryId: String(categoryId), priority: 30 } }), res);
  assert.equal(res.code, 200);
  assert.deepEqual(rule.conditions, conditions);
  assert.equal(rule.priority, 30);
  assert.equal(rule.autoGenerated, false);
  assert.equal(rule.learningKey, undefined);
});

test('invalid regexes and unsupported directions fail validation while priority zero is supported', () => {
  assert.throws(() => validateConditions([{ field: 'body', operator: 'regex', value: '[' }]), /regular expression/);
  assert.throws(() => validateConditions([{ field: 'direction', operator: 'equals', value: 'OTHER' }]), /Direction/);
  assert.throws(() => validateConditions([]), /conditions/);
  assert.equal(validatePriority(0), 0);
});
