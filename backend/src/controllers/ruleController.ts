import { Request, Response } from 'express';
import { RuleModel } from '../models/Rule';
import { CategoryModel } from '../models/Category';
import { Types } from 'mongoose';
import { validateConditions, validatePriority } from '../services/ruleValidation';

export class RuleController {
  public static async updateRule(req: Request, res: Response) {
    try {
      if (!Types.ObjectId.isValid(req.params.id)) return res.status(400).json({ success: false, error: 'Invalid rule ID' });
      const rule = await RuleModel.findById(req.params.id);
      if (!rule) return res.status(404).json({ success: false, error: 'Rule not found' });
      const categoryId = req.body.categoryId || String(rule.categoryId);
      if (!Types.ObjectId.isValid(categoryId) || !await CategoryModel.exists({ _id: categoryId })) return res.status(400).json({ success: false, error: 'Choose an existing category' });
      rule.conditions = validateConditions(req.body.conditions ?? rule.conditions);
      rule.priority = validatePriority(req.body.priority ?? rule.priority);
      rule.categoryId = new Types.ObjectId(categoryId);
      rule.autoGenerated = false;
      rule.learnedFrom = 'USER';
      rule.learningKey = undefined;
      await rule.save();
      res.json({ success: true, data: await RuleModel.findById(rule._id).populate('categoryId') });
    } catch (error: any) {
      res.status(error.status || 500).json({ success: false, error: error.message || 'Could not update rule' });
    }
  }

  public static async getRules(_req: Request, res: Response) {
    try {
      const rules = await RuleModel.find({}).populate('categoryId').sort({ priority: -1 });
      res.json({ success: true, count: rules.length, data: rules });
    } catch (error: any) {
      res.status(500).json({ success: false, error: error.message, data: [] });
    }
  }

  public static async createRule(req: Request, res: Response) {
    try {
      const { categoryId, customCategoryName, conditions, priority } = req.body;
      const normalizedConditions = validateConditions(conditions);
      const normalizedPriority = validatePriority(priority);
      if ((!categoryId && !customCategoryName) || !conditions || !Array.isArray(conditions) || conditions.length === 0) {
        return res.status(400).json({ success: false, error: 'Category selection or custom category name, and valid conditions are required' });
      }

      let finalCategoryId = categoryId;

      // Handle user-entered custom category
      if (customCategoryName && typeof customCategoryName === 'string' && customCategoryName.trim()) {
        const trimmed = customCategoryName.trim();
        const slug = trimmed.toLowerCase().replace(/[^a-z0-9]/g, '-');
        let category = await CategoryModel.findOne({
          $or: [{ name: { $regex: new RegExp(`^${trimmed.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`, 'i') } }, { slug }]
        });

        if (!category) {
          const vibrantPalette = ['#059669', '#10B981', '#0D9488', '#D97706', '#4F46E5', '#E11D48', '#8B5CF6'];
          const randomColor = vibrantPalette[Math.floor(Math.random() * vibrantPalette.length)];
          category = new CategoryModel({
            name: trimmed,
            slug,
            colorCode: randomColor,
            createdSource: 'USER'
          });
          await category.save();
        }
        finalCategoryId = category._id;
      }

      const rule = new RuleModel({
        categoryId: finalCategoryId,
        conditions: normalizedConditions,
        priority: normalizedPriority,
        autoGenerated: false
      });

      await rule.save();
      const populatedRule = await RuleModel.findById(rule._id).populate('categoryId');
      res.status(201).json({ success: true, data: populatedRule });
    } catch (error: any) {
      res.status(error.status || 500).json({ success: false, error: error.message });
    }
  }

  public static async deleteRule(req: Request, res: Response) {
    try {
      const { id } = req.params;
      await RuleModel.findByIdAndDelete(id);
      res.json({ success: true, message: 'Rule deleted successfully' });
    } catch (error: any) {
      res.status(500).json({ success: false, error: error.message });
    }
  }
}
