import type { DataSnapshot, EmailRecord } from './types';
import type { LocalOperation } from './outboxTypes';

export function projectOutbox(snapshot: DataSnapshot, operations: LocalOperation[]): DataSnapshot {
  const entries = new Map(snapshot.entries.map(row => [row._id, { ...row }]));
  const categories = new Map(snapshot.categories.map(row => [row._id, { ...row }]));
  const rules = new Map(snapshot.rules.map(row => [row._id, { ...row }]));
  let notifications = snapshot.notifications.slice();
  for (const op of operations.slice().sort((a, b) => a.sequence - b.sequence)) {
    const state = op.state === 'BLOCKED' ? 'blocked' : op.state === 'DONE' ? undefined : 'pending';
    const payload = op.payload;
    if (op.kind === 'category.create') categories.set(op.targetId, { _id: op.targetId, name: payload.name, slug: payload.name, colorCode: '#0f766e', createdSource: 'USER', ...op.result });
    if (op.kind === 'category.rename') { const row = categories.get(op.targetId); if (row) categories.set(op.targetId, { ...row, name: payload.name, ...op.result }); }
    if (op.kind.startsWith('entry.')) {
      const existing = entries.get(op.targetId) || (op.base as EmailRecord | undefined);
      const category = categories.get(payload.categoryId || existing?.categoryId?._id || '');
      let entry = existing;
      if (op.kind === 'entry.create') entry = { _id: op.targetId, messageId: `pending_${op.id}`, sender: 'Manual Transaction', subject: payload.title, rawTextBody: payload.notes || '', hasAttachments: false, categorySource: 'USER_MANUAL', needsUserReview: false, reviewStatus: 'APPROVED', receivedAt: new Date(payload.date || op.createdAt).toISOString(), processedAt: op.createdAt, parsedJson: { isManual: true } };
      if (entry) {
        if (op.kind === 'entry.create' || op.kind === 'entry.update') entry = { ...entry, subject: payload.title, receivedAt: new Date(payload.date || entry.receivedAt).toISOString(), categoryId: category, needsUserReview: false,
          parsedJson: { ...entry.parsedJson, detectedAmount: payload.amount, merchantName: payload.title, paymentMode: payload.paymentMode, transactionDirection: payload.transactionDirection, friendName: payload.friendName, notes: payload.notes } };
        if (op.kind === 'entry.category') entry = { ...entry, categoryId: category, needsUserReview: false };
        if (op.kind === 'entry.delete' && op.state === 'DONE') entries.delete(op.targetId);
        else entries.set(op.targetId, { ...entry, ...op.result, syncState: state, syncOperationId: op.id, pendingDelete: op.kind === 'entry.delete' });
      }
    }
    if (op.kind === 'rule.create' || op.kind === 'rule.update') {
      const category = categories.get(payload.categoryId);
      if (category) rules.set(op.targetId, { ...(rules.get(op.targetId) || {}), _id: op.targetId, categoryId: category, conditions: payload.conditions, priority: payload.priority, autoGenerated: false, ...op.result });
    }
    if (op.kind === 'rule.delete') rules.delete(op.targetId);
    if (op.kind === 'notification.read') notifications = notifications.map(row => row.id === op.targetId ? { ...row, read: true } : row);
    if (op.kind === 'notification.clear') notifications = notifications.filter(row => row.createdAt > payload.before);
  }
  return { ...snapshot, entries: [...entries.values()].map(entry => ({ ...entry, categoryId: entry.categoryId ? categories.get(entry.categoryId._id) || entry.categoryId : undefined })).sort((a, b) => b.receivedAt.localeCompare(a.receivedAt)), categories: [...categories.values()].sort((a, b) => a.name.localeCompare(b.name)), rules: [...rules.values()], notifications };
}
