export interface Category {
  _id: string;
  name: string;
  slug: string;
  colorCode: string;
  createdSource: 'SYSTEM' | 'USER';
}

export interface SyncStatus {
  schemaVersion: number;
  revision: string;
  lastSuccessfulIngestionAt: string | null;
  ingestionInProgress?: boolean;
}

export interface DataSnapshot extends SyncStatus {
  generatedAt: string;
  categories: Category[];
  entries: EmailRecord[];
  analytics: DashboardStats;
  rules: Rule[];
  notifications: NotificationItem[];
}

export interface EmailRecord {
  _id: string;
  messageId: string;
  sender: string;
  subject: string;
  rawTextBody: string;
  parsedJson: Record<string, any>;
  hasAttachments: boolean;
  ocrExtractedText?: string;
  categoryId?: Category;
  categorySource: 'RULE' | 'GROQ_AI' | 'USER_MANUAL' | 'UNASSIGNED';
  aiConfidenceScore?: number;
  needsUserReview: boolean;
  reviewStatus: 'PENDING' | 'APPROVED' | 'REASSIGNED';
  receivedAt: string;
  processedAt: string;
}

export interface Rule {
  _id: string;
  categoryId: Category;
  conditions: Array<{
    field: 'sender' | 'subject' | 'body';
    operator: 'contains' | 'equals' | 'startsWith' | 'regex';
    value: string;
  }>;
  priority: number;
  autoGenerated: boolean;
}

export interface NotificationItem {
  id: string;
  title: string;
  message: string;
  type: 'SYNC' | 'TRANSACTION' | 'REMINDER' | 'SECURITY' | 'REVIEW';
  createdAt: string;
  read: boolean;
}

export interface DashboardStats {
  period?: {
    startDate: string;
    endDate: string;
  };
  summary: {
    totalEmails: number;
    pendingReviews: number;
    totalFinancialAmount: number;
    averageAmount?: number;
    sources: {
      rule: number;
      ai: number;
      user: number;
    };
    aiAccuracyPercentage: number;
  };
  categoryBreakdown: Array<{
    categoryName: string;
    colorCode: string;
    count: number;
    totalAmount?: number;
  }>;
  paymentModeBreakdown?: Array<{
    mode: string;
    totalAmount: number;
    count: number;
  }>;
  dailyTrend?: Array<{
    date: string;
    totalAmount: number;
    count: number;
  }>;
  monthlyTrend?: Array<{
    month: string;
    totalAmount: number;
    count: number;
  }>;
  yearlyTrend?: Array<{ year: string; totalAmount: number; count: number }>;
}
